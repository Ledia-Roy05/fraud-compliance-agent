import requests
from typing import Dict, Any

class OllamaLLMService:
    """
    Service to handle 100% offline inference via Ollama for generating 
    human-readable compliance narratives and risk audit summaries.
    """
    def __init__(self, model_name: str = "llama3", base_url: str = "http://localhost:11434"):
        self.model_name = model_name
        self.base_url = f"{base_url}/api/generate"

    def generate_compliance_report(self, transaction: Dict[str, Any], evaluation: Dict[str, Any], scoring: Dict[str, Any]) -> str:
        prompt = f"""
You are an expert AI Financial Fraud and Compliance Auditor. Based on the transaction and multi-agent findings below, write a professional, concise executive summary and compliance decision in clear human language.

Transaction Details:
- Transaction ID: {transaction.get('transaction_id')}
- Amount: ${transaction.get('amount_usd', 0.0):,.2f}
- Sender Account: {transaction.get('sender_account')}
- Receiver Account: {transaction.get('receiver_account')}
- Location: {transaction.get('location')}
- Transaction Type: {transaction.get('transaction_type')}

Agent 1 (Risk Flagger) Findings:
- Risk Flags: {evaluation.get('flags')}

Agent 2 (Risk Scorer) Findings:
- Calculated Risk Score: {scoring.get('risk_score')}/100
- Compliance Tier: {scoring.get('compliance_tier')}

Provide a formal risk rationale and a recommended action for the compliance team. Keep it professional, structured, and easy to read.
"""

        payload = {
            "model": self.model_name,
            "prompt": prompt,
            "stream": False
        }

        try:
            response = requests.post(self.base_url, json=payload, timeout=None)
            if response.status_code == 200:
                
                return response.json().get("response", "No response generated by Ollama.")
            else:
                return f"Error: Ollama returned status code {response.status_code}."
        except requests.exceptions.ConnectionError:
            return "Warning: Could not connect to Ollama backend. Please ensure Ollama is running locally (`ollama serve`) to view the AI-generated narrative."
        except Exception as e:
            return f"Error generating LLM narrative: {str(e)}"